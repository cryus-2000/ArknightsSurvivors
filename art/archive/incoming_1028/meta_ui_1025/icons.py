def main():
    for k, rows in ICONS.items():
        assert len(rows) == 11 and all(len(r) == 11 for r in rows), k
    # 预览：每个图标放大 8 倍，白盘黑字 / 黑盘白字两种
    keys = list(ICONS)
    S = 8
    cell = 13 * S
    im = Image.new('RGB', (len(keys) * (cell + 8), cell * 2 + 24), (12, 16, 22))
    d = ImageDraw.Draw(im)
    for i, k in enumerate(keys):
        for row, (bg, fg) in enumerate([((12, 16, 22), (236, 240, 244)), ((236, 240, 244), (16, 24, 32))]):
            x0 = i * (cell + 8)
            y0 = row * (cell + 8)
            d.ellipse((x0, y0, x0 + cell, y0 + cell), fill=bg, outline=(236, 240, 244), width=S)
            for y, r in enumerate(ICONS[k]):
                for x, ch in enumerate(r):
                    if ch == '#':
                        d.rectangle((x0 + (x + 1) * S, y0 + (y + 1) * S, x0 + (x + 2) * S - 1, y0 + (y + 2) * S - 1), fill=fg)
    im.save(ROOT / 'build/meta_ui/icons.png')
    lines = ['extends RefCounted',
             '## 认知塑造节点图标（11×11 像素，# = 主色）：art/archive/incoming_1028/meta_ui_1025/icons.py 生成，别手改。',
             '## 图形取原作「认知塑造」各系列的意象重画；键 = 节点 id 前缀（调度四节各一张）或 cell（生机细胞）',
             '', 'const ICONS := {']
    for k, rows in ICONS.items():
        lines.append('\t"%s": [%s],' % (k, ', '.join('"%s"' % r for r in rows)))
    lines += ['}', '', 'static var _tex := {}', '', '',
              '## 图标贴图（白色，调用方 modulate 上色）；没有的键回落到前缀',
              'static func tex(key: String) -> ImageTexture:',
              '\tif not ICONS.has(key):',
              '\t\tkey = key.rstrip("0123456789")',
              '\tif not ICONS.has(key):',
              '\t\tkey = "cell"',
              '\tif _tex.has(key):',
              '\t\treturn _tex[key]',
              '\tvar im := Image.create(11, 11, false, Image.FORMAT_RGBA8)',
              '\tvar rows: Array = ICONS[key]',
              '\tfor y in 11:',
              '\t\tfor x in 11:',
              '\t\t\tif str(rows[y])[x] == "#":',
              '\t\t\t\tim.set_pixel(x, y, Color.WHITE)',
              '\tvar t := ImageTexture.create_from_image(im)',
              '\t_tex[key] = t',
              '\treturn t', '']
    (ROOT / 'game/scripts/screens/meta_icons.gd').write_text('\n'.join(lines), encoding='utf-8')
    print('ok', len(keys))


if __name__ == '__main__':
    main()
