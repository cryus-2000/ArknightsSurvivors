const {createRequire}=require('module');
const dep=process.env.CODEX_NODE_MODULES||'C:/Users/colafax/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules';
const req=createRequire(dep+'/playwright/package.json');
const {chromium}=req('playwright');
const fs=require('fs'),path=require('path'),assert=require('assert');
const {pathToFileURL}=require('url');
const {PNG}=req('pngjs');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1280,height:850},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'review.html')).href);
  await page.waitForFunction(()=>window.settlementReview?.state.loaded);
  await page.evaluate(()=>settlementReview.seek(400));
  await page.locator('canvas').screenshot({path:path.join(__dirname,'midpoint.png')});
  await page.click('#finish');
  await page.locator('canvas').screenshot({path:path.join(__dirname,'completed.png')});
  const a=PNG.sync.read(fs.readFileSync(path.join(__dirname,'completed.png')));
  const b=PNG.sync.read(fs.readFileSync(path.join(__dirname,'../settlement/settlement_desktop.png')));
  assert.equal(a.width,b.width);assert.equal(a.height,b.height);assert(a.data.equals(b.data),'Final canvas differs from approved image');
  const mid=PNG.sync.read(fs.readFileSync(path.join(__dirname,'midpoint.png')));
  assert(!mid.data.equals(a.data),'Animation does not change pixels');
  await page.click('#replay');await page.click('#pause');
  const frozen=await page.evaluate(()=>settlementReview.state.elapsed);
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(()=>settlementReview.state.elapsed),frozen);
  await page.click('#pause');await page.waitForFunction(()=>settlementReview.state.elapsed===900);
  await page.check('#reduce');await page.click('#replay');
  assert.equal(await page.evaluate(()=>settlementReview.state.elapsed),900);
  await page.uncheck('#reduce');await page.click('#replay');await page.locator('canvas').click();
  assert.equal(await page.evaluate(()=>settlementReview.state.elapsed),900);
  await page.emulateMedia({reducedMotion:'reduce'});await page.reload();
  await page.waitForFunction(()=>window.settlementReview?.state.loaded);
  assert.equal(await page.evaluate(()=>settlementReview.state.elapsed),900);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(__dirname,'qa.json'),JSON.stringify({passed:true,checks:['Final frame pixel-identical to approved 1280x720 still','Visible midpoint animation','Pause freezes time; resume completes','900 ms completion','Reduce-motion toggle skips animation','System reduced-motion respected','Canvas click skips','No browser errors'],runtime_integrated:false},null,2));
  await browser.close();console.log('Settlement motion QA passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
