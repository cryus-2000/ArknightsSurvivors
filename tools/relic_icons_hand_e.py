def shift(rows, dx):
    """整图向右平移 dx 像素（只用于把画偏了的图居中）。"""
    out = []
    for r in rows:
        r2 = "." * dx + r[:32 - dx] if dx >= 0 else r[-dx:] + "." * (-dx)
        out.append(r2)
    return out


