ORDER = ["A", "B", "C", "D", "E", "F", "H", "M", "N", "Q", "0", "1", "5", "7"]

FILL = (201, 208, 255, 255)
SHADE = (125, 138, 239, 255)
EDGE = (51, 53, 151, 255)
GLOW = (79, 85, 190, 90)


def mask(ch):
    rows = [r for r in G[ch].strip("\n").split("\n")]
    assert len(rows) == 13, (ch, len(rows))
    for r in rows:
        assert len(r) == 13, (ch, r, len(r))
    return [[c == "#" for c in r] for r in rows]


def render(ch, cell, k):
    m = mask(ch)
    img = Image.new("RGBA", (cell, cell), (0, 0, 0, 0))
    px = img.load()
    # 按字形的实际外框居中（有的字只占上半截）
    ys = [y for y in range(13) if any(m[y])]
    xs = [x for x in range(13) if any(m[y][x] for y in range(13))]
    gh = (max(ys) - min(ys) + 1) * k
    gw = (max(xs) - min(xs) + 1) * k
    oy = (cell - gh) // 2 - min(ys) * k
    ox = (cell - gw) // 2 - min(xs) * k
    split = (cell - gh) // 2 + gh * 0.62
    # 字形 + 下半暗面
    for y in range(13):
        for x in range(13):
            if not m[y][x]:
                continue
            for dy in range(k):
                for dx in range(k):
                    yy = oy + y * k + dy
                    px[ox + x * k + dx, yy] = SHADE if yy >= split else FILL
    solid = [[px[x, y][3] > 0 for x in range(cell)] for y in range(cell)]
    # 1 像素描边 + 外面一圈半透明发光
    for y in range(cell):
        for x in range(cell):
            if solid[y][x]:
                continue
            near = any(0 <= x + dx < cell and 0 <= y + dy < cell and solid[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
            if near:
                px[x, y] = EDGE
    solid2 = [[px[x, y][3] > 0 for x in range(cell)] for y in range(cell)]
    for y in range(cell):
        for x in range(cell):
            if solid2[y][x]:
                continue
            near = any(0 <= x + dx < cell and 0 <= y + dy < cell and solid2[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
            if near:
                px[x, y] = GLOW
    return img


def sheet(cell, k):
    out = Image.new("RGBA", (cell * len(ORDER), cell), (0, 0, 0, 0))
    for i, ch in enumerate(ORDER):
        out.paste(render(ch, cell, k), (i * cell, 0))
    return out


