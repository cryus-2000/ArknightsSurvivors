def stamp(rows, mark, x0=22, y0=21):
    """把 7×7 小标盖到底图上（'.' 不改），返回新行列表。"""
    out = [list(r) for r in rows]
    for j, mr in enumerate(MARKS[mark]):
        for i, ch in enumerate(mr):
            if ch != ".":
                out[y0 + j][x0 + i] = ch
    return ["".join(r) for r in out]


